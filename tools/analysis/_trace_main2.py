def disasm(bank, start, length):
    p = start
    end = start + length
    rom_start = r(bank, 0)
    while p < end:
        addr = r(bank, p)
        if addr >= len(rom):
            break
        size, txt = peek(bank, p)
        print(f'  ${bank:02X}:{p:04X} ({addr:06X}): {txt}')
        p += size

