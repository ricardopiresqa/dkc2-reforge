"""Export Rambi (animal buddy), Diddy's riding pose and the ship-deck breakable wall.

Animations (F9 frame ops only): idle $14A, walk (frames of $14F after its Hurt frame),
jump $11D, turn $66. Rider: Diddy RideAnimalBuddy pose $211C (animation $52), drawn at the
animal's origin: the rider poses are authored relative to it (checked on idle, walk and
jump). Wall: BreakableWall level object (param 3360) pose $2FD8, palette index $3E
(Sprite_BreakableWall_ShipDeck), spawn fields $42 = 3 (bonus 2), $44 = 4 (return record).
Writes data/original/pirate/rambi.lua and assets/images/pirate/rambi/.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(ROOT / "tools"))
import export_diddy_moves as moves  # noqa: E402
import export_items as items  # noqa: E402
import export_walkers as walkers  # noqa: E402
from gfx_convert import load_palette  # noqa: E402

OUT = ROOT / "assets/images/pirate/rambi"
ANIMATIONS = {"idle": 0x14A, "walk": 0x14F, "jump": 0x11D, "turn": 0x66}
RIDER_POSE, WALL_POSE = 0x211C, 0x2FD8


def frames(rom, number, name_of):
    data = moves.script(rom, number)
    out = [(op["op"], op["arg"]) for op in data["code"].values() if op["op"] < 0x80]
    if number == 0x14F:  # $14F = hurt then run: keep the run cycle
        out = [frame for frame in out if "Hurt" not in name_of(frame[1])]
    return out


def export():
    rom = items.ROM.read_bytes()
    name_of = items.pose_names(rom)
    rambi_palette = load_palette(str(items.SOURCE / "Palettes" / "Sprite_Rambi.bin"))
    diddy_palette = load_palette(str(items.SOURCE / "Palettes" / "Sprite_Diddy_Active.bin"))
    wall_palette = load_palette(str(items.SOURCE / "Palettes" / items.palette_file(0x3E)))
    OUT.mkdir(parents=True, exist_ok=True)
    poses = {}

    def add(pose, palette):
        if pose in poses:
            return
        image, origin_x, origin_y = items.render(name_of(pose), palette)
        sprite = "original_rambi_%04x" % pose
        image.save(OUT / (sprite + ".png"))
        poses[pose] = (sprite, origin_x, origin_y, image.width, image.height, walkers.hitbox(rom, pose))

    animations = {}
    for key, number in ANIMATIONS.items():
        animations[key] = frames(rom, number, name_of)
        for _, pose in animations[key]:
            add(pose, rambi_palette)
    add(RIDER_POSE, diddy_palette)
    add(WALL_POSE, wall_palette)
    lines = ["-- Generated by tools/replay-compare/export_rambi.py.", "return {",
             "  rider = %d, wall = { pose = %d, dest = 'bonus_2', return_record = 4, param = 3360 }," % (RIDER_POSE, WALL_POSE),
             "  animations = {"]
    for key, list_ in animations.items():
        lines.append("    %s = { %s }," % (key, ", ".join("{ %d, %d }" % frame for frame in list_)))
    lines.append("  },")
    lines.append("  poses = {")
    for pose, (sprite, ox, oy, width, height, box) in sorted(poses.items()):
        lines.append('    [%d] = { sprite = "%s", origin_x = %d, origin_y = %d, width = %d, height = %d, box = { %d, %d, %d, %d } },'
                     % ((pose, sprite, ox, oy, width, height) + tuple(box)))
    lines += ["  },", "}"]
    (ROOT / "data/original/pirate/rambi.lua").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return {key: len(value) for key, value in animations.items()}, len(poses)


if __name__ == "__main__":
    print(export())
