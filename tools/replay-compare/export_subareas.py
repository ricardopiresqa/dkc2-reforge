"""Export Pirate Panic's ship-deck subareas (bonus 1, bonus 2, warp) as playable rooms.

Source: the same decompressed map as the main area (LevelData/ShipDeckLevels.bin,
assets-raw/pirate/_decoded) and the ship-deck area table DATA_B5BE25 ({start, end,
y start, y end, flags} in map bytes = pixels; the table spans exactly $7380 = the
decoded size). The area index is the level header's preamble byte (main 0, warp 4,
bonus 1 5, bonus 2 6; all share descriptor DATA_FD4996). Room-local coordinates are
x_raw/y_raw - $100 from the area start (spawns land on the floors; bonus-2 enemies sit
on the drawn barrels). Objects and spawns come from the generated level module.
Writes data/original/pirate/subarea_<name>.lua and assets/images/pirate/subareas/.
The Captain's Kabin uses another descriptor (DATA_FD4BB8) and is not handled here.
"""
import re
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools"))
import import_pirate_panic as ip  # noqa: E402

DECODED = ROOT / "assets-raw/pirate/_decoded"
SOURCE = ROOT / "tools/vendor/DKC2-disasm/DKC2"
OUT = ROOT / "assets/images/pirate/subareas"
# DATA_B5BE25 entries (map bytes): area index -> (start, end, y_start, y_end)
AREAS = {"warp": (4, 0x64A0, 0x65A0, 0x0000, 0x0200),
         "bonus_1": (5, 0x65A0, 0x67A0, 0x0000, 0x0200),
         "bonus_2": (6, 0x67A0, 0x6CA0, 0x0000, 0x0100)}
LEVEL_IDS = {"warp": 29, "bonus_1": 111, "bonus_2": 112}


def level_objects(name):
    text = (ROOT / "data/original/pirate/pirate_panic_level.lua").read_text(encoding="utf-8")
    block = text.split("    %s = {" % name, 1)[1].split("header = {", 1)
    objects = re.findall(r"\{ type = (\d+), script = (\d+), class = (\d+), x = (-?\d+), feet_y = (-?\d+), "
                         r"param = (\d+), sprite = '([^']+)' \}", block[0])
    records = re.findall(r"\{ flags = (\d+), x = (-?\d+), feet_y = (-?\d+) \}", block[1].split("post_record", 1)[0])
    return objects, records


# Main-area portals (barrel cannons $140, pose $8CC): the data the cannon reads after its
# spawn script holds {destination index, return record} (params 332: $0203, 398: $0405),
# indexes into the main header's linked levels [12, 27, 111, 112, 29].
PORTALS = {332: ("bonus_1", 3), 398: ("warp", 5)}
# Bonus controllers (spawn sub-script D354: $42 type, $44 count, $46 seconds).
CONTROLLERS = {3560: (0, 0, 0x14), 3402: (1, 7, 0x14)}
CANNON_POSE = 0x8CC


def export_links(rom):
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import export_items as items
    import export_walkers as walkers
    from gfx_convert import load_palette
    palette = load_palette(str(items.SOURCE / "Palettes" / items.palette_file(2)))
    image, origin_x, origin_y = items.render(items.pose_names(rom)(CANNON_POSE), palette)
    image.save(OUT / "original_barrel_cannon.png")
    box = walkers.hitbox(rom, CANNON_POSE)
    main = ip.parse_level_header(rom, 3)
    text = (ROOT / "data/original/pirate/pirate_panic_level.lua").read_text(encoding="utf-8").split("subareas = {")[0]
    portals = []
    for x, feet, param in re.findall(r"x = (-?\d+), feet_y = (-?\d+), param = (\d+), sprite = 'BarrelCannon'", text):
        if int(param) in PORTALS:
            dest, ret = PORTALS[int(param)]
            # Spawn op $8A word bit $0008 sets $1C = $C000 (B3E7C4): the cannon is invisible
            # (398 = $200C, the warp; 332 = $2004). Revealed when a Kong gets in.
            hidden = bool(items.spawn_fields(rom, int(param)).get("op8a", 0) & 0x0008)
            portals.append('    { x = %s, feet_y = %s, param = %s, dest = "%s", return_record = %d, hidden = %s },'
                           % (x, feet, param, dest, ret, "true" if hidden else "false"))
    lines = ["-- Generated by tools/replay-compare/export_subareas.py (area links).", "return {",
             '  cannon = { sprite = "original_barrel_cannon", origin_x = %d, origin_y = %d, width = %d, height = %d,'
             ' box = { %d, %d, %d, %d } },' % ((origin_x, origin_y, image.width, image.height) + tuple(box)),
             "  portals = {"] + portals + ["  },", "  main_records = {"]
    lines += ["    [%d] = { x = %d, feet_y = %d }," % (r["index"], r["x"], r["feet_y"]) for r in main["records"]]
    lines += ["  },", "  controllers = {"]
    lines += ["    [%d] = { kind = %d, count = %d, seconds = %d }," % ((param,) + c) for param, c in CONTROLLERS.items()]
    lines += ["  },", "}"]
    (ROOT / "data/original/pirate/area_links.lua").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return len(portals)


def export_kabin():
    """Captain's Kabin: a single BG screen (Tilemaps/Compressed/Layer1_Level_KaptainsKabin,
    descriptor DATA_FD4BB8), not a ship-deck metatile area. No collision map is decoded
    for it; measured instead (kabin-route-t1..t3.csv, kabin_probe_capture.lua): the floor
    is flat at feet 192 from wall to door and the Kong stops at x 16 on the left (port
    player box 16 wide -> columns 0-8 solid). APPROXIMATION: the room is a box (no table
    platform found along the floor walk)."""
    tilemap = ip.cmp_decompress((SOURCE / "Tilemaps/Compressed/Layer1_Level_KaptainsKabin.bin").read_bytes())
    gfx = ip.cmp_decompress((SOURCE / "Graphics/Compressed/GFX_Layer1_Level_KaptainsKabin.bin").read_bytes())
    raw_palette = (SOURCE / "Palettes/FGBG_Level_KaptainsKabin.bin").read_bytes()
    palette = [ip.decode_bgr555_word(raw_palette[i] | raw_palette[i + 1] << 8)
               for i in range(0, len(raw_palette) - 1, 2)] + [(0, 0, 0)] * 128
    tiles = ip.decode_gfx_4bpp(gfx)
    from PIL import Image
    width, height = 256, len(tilemap) // 2 // 32 * 8
    image = Image.new("RGBA", (width, height), (0, 0, 0, 255))
    pixels = image.load()
    for index in range(len(tilemap) // 2):
        word = tilemap[2 * index] | tilemap[2 * index + 1] << 8
        tile = word & 0x3FF
        if tile >= len(tiles):
            continue
        for y in range(8):
            for x in range(8):
                colour = ip.tile_pixel(tiles, tile, palette, x, y, bool(word & 0x4000), bool(word & 0x8000),
                                       (word >> 10) & 7)
                if colour is not None:
                    pixels[(index % 32) * 8 + x, (index // 32) * 8 + y] = (*colour, 255)
    image.save(OUT / "subareakabin0chunk.png")
    rows = 16
    heights = [-1] * (width * rows)
    for x in range(width):
        heights[6 * width + x] = 32  # row 6: surface = 6 * 32 + 32 - 32 = 192 (feet row)
    for x in range(9):  # left wall: the Kong stops at x 16
        for row in range(6):
            heights[row * width + x] = 32
    objects, records = level_objects("captains_kabin")
    lines = ["-- Generated by tools/replay-compare/export_subareas.py (Captain's Kabin, DATA_FD4BB8).",
             "return {", "  name = 'kabin', level_id = 27, area_index = 0,",
             "  width_px = %d, height_px = %d," % (width, height),
             "  surface_cols = %d, surface_rows = %d, surface_rle = '%s'," % (width, rows, ip.rle_encode(heights)),
             "  spawns = {"]
    lines += ["    { flags = %s, x = %s, feet_y = %s }," % record for record in records]
    lines += ["  },", "  chunks = {", "    { anim = 'subareakabin0chunk', x = 0, w = %d, h = %d }," % (width, height),
              "  },", "  objects = {"]
    lines += ["    { type = %s, script = %s, class = %s, x = %s, feet_y = %s, param = %s, sprite = '%s' },"
              % obj for obj in objects]
    lines += ["  },", "}"]
    (ROOT / "data/original/pirate/subarea_kabin.lua").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return image.size


def export_kabin_note():
    """K. Rool's note text (kabin-route-t5.csv): walking into the note shows the message at
    once (frame 828; 826 is the same screen without it) and it stays. The overlay keeps the
    pixels that changed between those frames in the text rows (36-95), minus the floating
    balloon (x < 60 below row 72). Output: subareas/original_kabin_note_text.png + box."""
    from PIL import Image, ImageChops

    def load(frame):
        image = Image.open(ROOT / ("assets-raw/pirate/kabin-t5-frame-%04d.ppm" % frame)).convert("RGB")
        return image.crop((0, 7, 256, 231)) if image.height > 224 else image
    before, after = load(826), load(828)
    mask = ImageChops.difference(before, after).convert("L").point(lambda v: 255 if v > 8 else 0)
    keep = Image.new("L", mask.size, 0)
    keep.paste(255, (0, 36, 256, 96))
    keep.paste(0, (0, 72, 60, 96))
    mask = ImageChops.multiply(mask, keep)
    box = mask.getbbox()
    overlay = after.convert("RGBA")
    overlay.putalpha(mask)
    overlay.crop(box).save(OUT / "original_kabin_note_text.png")
    return box


def export():
    rom = (SOURCE / "Donkey Kong Country 2 (USA V1.0).sfc").read_bytes()
    map_raw = (DECODED / "LevelData_ShipDeckLevels.bin").read_bytes()
    defs = (DECODED / "Tilemaps_Map32_Layer1_Level_ShipDeck.bin").read_bytes()
    gfx = (DECODED / "Graphics_Compressed_GFX_Layer1_Level_ShipDeck.bin").read_bytes()
    raw_palette = (SOURCE / "Palettes/FGBG_Level_PiratePanic.bin").read_bytes()
    palette = [ip.decode_bgr555_word(raw_palette[i] | raw_palette[i + 1] << 8)
               for i in range(0, len(raw_palette) - 1, 2)]
    palette += [(0, 0, 0)] * (128 - len(palette))
    props = ip.collision_property_map(rom)
    OUT.mkdir(parents=True, exist_ok=True)
    report = {}
    for name, (index, start, end, y_start, y_end) in AREAS.items():
        area_map = map_raw[start:end]
        image = ip.render_level(area_map, defs, gfx, palette).crop((0, y_start, end - start, y_end))
        chunks = []
        for chunk_index, x in enumerate(range(0, image.width, 512)):
            width = min(512, image.width - x)
            sprite = "subarea%s%dchunk" % (name.replace("_", ""), chunk_index)
            image.crop((x, 0, x + width, image.height)).save(OUT / (sprite + ".png"))
            chunks.append((sprite, x, width, image.height))
        surfaces = ip.build_flat_surfaces(area_map, props, rom, (end - start) // 32)
        objects, records = level_objects(name)
        lines = ["-- Generated by tools/replay-compare/export_subareas.py (ShipDeckLevels area %d, DATA_B5BE25)."
                 % index,
                 "return {",
                 "  name = '%s', level_id = %d, area_index = %d," % (name, LEVEL_IDS[name], index),
                 "  width_px = %d, height_px = %d," % (image.width, image.height),
                 "  surface_cols = %d, surface_rows = %d, surface_rle = '%s',"
                 % (surfaces["cols"], surfaces["rows"], surfaces["rle"]),
                 "  spawns = {"]
        lines += ["    { flags = %s, x = %s, feet_y = %s }," % record for record in records]
        lines.append("  },")
        lines.append("  chunks = {")
        lines += ["    { anim = '%s', x = %d, w = %d, h = %d }," % chunk for chunk in chunks]
        lines.append("  },")
        lines.append("  objects = {")
        lines += ["    { type = %s, script = %s, class = %s, x = %s, feet_y = %s, param = %s, sprite = '%s' },"
                  % obj for obj in objects]
        lines += ["  },", "}"]
        (ROOT / ("data/original/pirate/subarea_%s.lua" % name)).write_text("\n".join(lines) + "\n", encoding="utf-8")
        report[name] = (image.size, len(chunks), len(objects), surfaces["unknown_cells"])
    report["portals"] = export_links(rom)
    report["kabin"] = export_kabin()
    return report


if __name__ == "__main__":
    for name, info in export().items():
        print(name, info)
