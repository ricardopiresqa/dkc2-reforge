"""Export the burst and smoke-puff effects (BurstEffect $238 anim $168, sprite $23C anim $1BB).

Evidence (route-bot-trace.csv): a wooden box breaking on a Neek (frame 1230) spawns the
burst (21 frames) and the smoke puff (falling 1 px every 2 frames) at the impact; the hit
that kills Diddy (frame 1260) spawns the burst at the contact point. Palette: OBJ palette 0
(Sprite_HUDNumbers, the shared one the DK emblem also uses) gives the original colours.
Barrel shards (sprites $60/$64, anims $2A4/$2A5; route-bot-trace.csv frames 1230 and
2042): four pieces per break in OBJ palette slot 4, the slot holding Sprite_Barrel (the
wooden box and DK barrel palette, spawn field $8D = 2).
Their poses ($258-$294) are static: a 5-byte header (16x16 count, 8x8 count, first tile,
second-group count/first tile) then (x, y) pairs biased 128, tiles read from VRAM. The
pieces live at OBJ tiles $80 ($2A4) and $60 ($2A5), OBJ base 0 (goal-t7-frame-4946: the
pose fields $1A $260/$280 against the OAM tiles $87/$68; pole $C0 and target $140 match
their ROM tiles at the same base). OBJ slot 3 there holds Sprite_Barrel.
Writes data/original/pirate/effects.lua and assets/images/pirate/effects/.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(ROOT / "tools"))
import export_diddy_moves as moves  # noqa: E402
import export_items as items  # noqa: E402
from gfx_convert import decode_tile, load_palette  # noqa: E402

OUT = ROOT / "assets/images/pirate/effects"
EFFECTS = {"burst": 0x168, "smoke": 0x1BB}
SHARDS = {"shard_a": 0x2A4, "shard_b": 0x2A5}
SHARD_TILES = {0x2A4: 0x80, 0x2A5: 0x60}
VRAM = ROOT / "assets-raw/pirate/goal-t7-frame-4946-vram.bin"


def render_static(rom, offset, vram, first_tile, palette):
    """Static pose -> (image, origin_x, origin_y); 8x8 pieces only (the shards have no 16x16)."""
    header = (rom[0x3C8000 + offset] | rom[0x3C8001 + offset] << 8 | rom[0x3C8002 + offset] << 16) & 0x3FFFFF
    big, small, start = rom[header], rom[header + 1], rom[header + 2]
    assert big == 0 and rom[header + 3] == 0, "static pose %x: only one 8x8 group is supported" % offset
    pieces = [(rom[header + 5 + 2 * i] - 128, rom[header + 6 + 2 * i] - 128, first_tile + start + i) for i in range(small)]
    left, top = min(p[0] for p in pieces), min(p[1] for p in pieces)
    image = moves.Image.new("RGBA", (max(p[0] for p in pieces) - left + 8, max(p[1] for p in pieces) - top + 8))
    for x, y, tile in pieces:
        for row, line in enumerate(decode_tile(vram[tile * 32:tile * 32 + 32])):
            for column, index in enumerate(line):
                if index:
                    image.putpixel((x - left + column, y - top + row), tuple(palette[index][:3]) + (255,))
    return image, -left, -top


def export():
    rom = items.ROM.read_bytes()
    name_of = items.pose_names(rom)
    hud_palette = load_palette(str(items.SOURCE / "Palettes" / "Sprite_HUDNumbers.bin"))
    barrel_palette = load_palette(str(items.SOURCE / "Palettes" / "Sprite_Barrel.bin"))
    vram = VRAM.read_bytes()
    OUT.mkdir(parents=True, exist_ok=True)
    added = {}
    lines = ["-- Generated by tools/replay-compare/export_effects.py.", "return {"]
    for key, number in list(EFFECTS.items()) + list(SHARDS.items()):
        palette = barrel_palette if key in SHARDS else hud_palette
        frames = []
        for op in moves.script(rom, number)["code"].values():
            if op["op"] < 0x80:
                if key in SHARDS:
                    image, origin_x, origin_y = render_static(rom, op["arg"], vram, SHARD_TILES[number], palette)
                else:
                    image, origin_x, origin_y = items.render(name_of(op["arg"]), palette)
                sprite = "original_effect_%04x" % op["arg"]
                image.save(OUT / (sprite + ".png"))
                added[sprite] = ["/assets/images/pirate/effects/%s.png" % sprite]
                frames.append('{ sprite = "%s", frames = %d, origin_x = %d, origin_y = %d, width = %d, height = %d }'
                              % (sprite, op["op"], origin_x, origin_y, image.width, image.height))
        lines.append("  %s = { %s }," % (key, ", ".join(frames)))
    lines.append("}")
    (ROOT / "data/original/pirate/effects.lua").write_text("\n".join(lines) + "\n", encoding="utf-8")
    moves.insert_atlas_groups(added)


if __name__ == "__main__":
    export()
    print((ROOT / "data/original/pirate/effects.lua").read_text()[:300])
