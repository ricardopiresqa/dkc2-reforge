"""Opening (Rare logo, Nintendo presents, copyright, title) from the captured boot frames.

Input: assets-raw/pirate/opening/frame-NNNN.ppm (opening_frames_capture.lua, every 10
frames from 150 to 800, no input). Output: 256x224 PNGs (overscan rows 7..230 cropped as
in the other screen comparisons) under assets/images/pirate/title, consecutive duplicates
dropped, and data/original/pirate/opening.lua = { {frame, sprite}, ... } in boot frames.
"""
import re
import sys
from pathlib import Path

from PIL import Image, ImageChops

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "assets-raw/pirate/opening"
OUT = ROOT / "assets/images/pirate/title"


def export():
    OUT.mkdir(parents=True, exist_ok=True)
    entries, previous = [], None
    for path in sorted(SOURCE.glob("frame-*.ppm")):
        frame = int(path.stem.split("-")[1])
        image = Image.open(path).convert("RGB")
        image = image.crop((0, 7, 256, 231)) if image.height > 224 else image
        if previous is not None and ImageChops.difference(image, previous).getbbox() is None:
            continue
        name = "original_opening_f%04d" % frame
        image.save(OUT / (name + ".png"))
        entries.append((frame, name))
        previous = image
    lines = ["-- Generated by tools/replay-compare/export_opening.py (boot frames, no input).",
             "return {"]
    lines += ['  { frame = %d, sprite = "%s" },' % entry for entry in entries]
    lines.append("}")
    (ROOT / "data/original/pirate/opening.lua").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return entries


FULL_RATE = ROOT / "assets-raw/pirate/opening60"
TITLE_RATE = ROOT / "assets-raw/pirate/title60"
# title60_capture.lua (frames 800-1700): the fade-in (800-850) is the steady title dimmed
# (brightness steps every 2 frames, mean error ~3/255 against the scaled picture), then
# the chest sparkles change every ~4 frames inside one box (no period in 850 frames).
TITLE_FADE_END, TITLE_END = 850, 1700


def export_title(groups):
    """Title as data: the steady picture, the fade ratios (one per frame from 800) and the
    sparkle patches (box crops, one per distinct frame), looped over 850-1700."""
    def load(frame):
        image = Image.open(TITLE_RATE / ("frame-%04d.ppm" % frame)).convert("RGB")
        return image.crop((0, 7, 256, 231)) if image.height > 224 else image
    base = load(TITLE_FADE_END)
    luma = sum(base.convert("L").getdata()) or 1
    fade = [round(sum(load(frame).convert("L").getdata()) / luma, 3) for frame in range(800, TITLE_FADE_END)]
    box = None
    for frame in range(TITLE_FADE_END, TITLE_END + 1):
        b = ImageChops.difference(load(frame), base).getbbox()
        if b:
            box = b if box is None else (min(box[0], b[0]), min(box[1], b[1]), max(box[2], b[2]), max(box[3], b[3]))
    base.save(OUT / "original_title_base.png")
    groups["original_title_base"] = ["/assets/images/pirate/title/original_title_base.png"]
    sparkles, previous, seen = [], None, {}
    for frame in range(TITLE_FADE_END, TITLE_END + 1):
        patch = load(frame).crop(box)
        if previous is not None and ImageChops.difference(patch, previous).getbbox() is None:
            continue
        previous = patch
        key = patch.tobytes()
        if key not in seen:
            seen[key] = "original_title_sparkle_%03d" % len(seen)
            patch.save(OUT / (seen[key] + ".png"))
            groups[seen[key]] = ["/assets/images/pirate/title/%s.png" % seen[key]]
        sparkles.append('    { %d, "%s" },' % (frame, seen[key]))
    return (["  title = {", '    base = "original_title_base", from = 800, steady = %d, loop_end = %d,'
             % (TITLE_FADE_END, TITLE_END),
             "    fade = { %s }," % ", ".join(str(v) for v in fade),
             "    box = { %d, %d, %d, %d }," % (box[0], box[1], box[2] - box[0], box[3] - box[1]),
             "    sparkles = {"] + ["  " + line for line in sparkles] + ["    },", "  },"])
# opening60_capture.lua runs 2 frames ahead of the 10-frame capture (mean-luminance fit
# over 150-800: shift -2), whose timeline the title frames (>= 800) keep.
FULL_RATE_SHIFT, FULL_RATE_END = 2, 800


def export_full_rate():
    """Logos at 60 fps: every distinct boot frame from opening60 up to FULL_RATE_END,
    cropped to its non-black box (x, y, w, h on the 256x224 screen; a black frame has no
    sprite), then the title from title60 (export_title). Rewrites opening.lua and inserts
    the new atlas entries; the old 10-frame entries' atlas entries are dropped."""
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import export_diddy_moves as moves
    entries, previous, groups = [], None, {}
    for path in sorted(FULL_RATE.glob("frame-*.ppm")):
        frame = int(path.stem.split("-")[1]) + FULL_RATE_SHIFT
        if frame >= FULL_RATE_END:
            break
        image = Image.open(path).convert("RGB")
        # The Nintendo logo (430-590) is a hi-res screen: 512x478 (double width and
        # lines). Kept at that resolution (overscan rows 14..461) and drawn at half scale.
        hires = image.width == 512
        if hires:
            image = image.crop((0, 14, 512, 462))
        elif image.height > 224:
            image = image.crop((0, 7, 256, 231))
        if previous is not None and previous.size == image.size                 and ImageChops.difference(image, previous).getbbox() is None:
            continue
        previous = image
        box = image.getbbox()
        if box is None:
            entries.append('  { frame = %d },' % frame)
            continue
        name = "original_opening60_f%04d" % frame
        image.crop(box).save(OUT / (name + ".png"))
        groups[name] = ["/assets/images/pirate/title/%s.png" % name]
        scale = 2 if hires else 1
        entries.append('  { frame = %d, sprite = "%s", x = %g, y = %g, w = %g, h = %g%s },'
                       % ((frame, name) + tuple(v / scale for v in (box[0], box[1], box[2] - box[0], box[3] - box[1]))
                          + (", scale = 0.5" if hires else "",)))
    title_lines = export_title(groups)
    lines = ["-- Generated by tools/replay-compare/export_opening.py (boot frames, no input; logos at",
             "-- full rate from opening60, title from title60).", "return {"] + entries + title_lines + ["}"]
    (ROOT / "data/original/pirate/opening.lua").write_text("\n".join(lines) + "\n", encoding="utf-8")
    moves.insert_atlas_groups(groups)
    atlas = moves.ATLAS.read_text(encoding="utf-8")
    for frame_name in set(re.findall(r'id: "(original_opening_f\d{4})"', atlas)):
        # the frame's group and its per-image id (insert_atlas_groups adds "<name>" for "<name>.png")
        atlas = re.sub(r'animations \{\n  id: "%s"\n(?:  .*\n)*?\}\n' % frame_name, "", atlas)
    moves.ATLAS.write_text(atlas, encoding="utf-8")
    return len(entries)


if __name__ == "__main__" and "--full-rate" in sys.argv:
    print(export_full_rate())
    sys.exit(0)

if __name__ == "__main__":
    entries = export()
    print(len(entries), entries[0], entries[-1])
