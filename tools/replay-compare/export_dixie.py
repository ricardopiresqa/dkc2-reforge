"""Export the partner Kong animations: Dixie's player moves and both Kongs' follower moves.

The engine picks a Kong's animation script as id + $A3 for every Kong but Diddy (B9D0B8:
slot $16B2 = Diddy keeps the id). Scripts are decoded with export_diddy_moves.script and
keyed by the base id; poses are rendered with each Kong's palette (Dixie on a 128x128 canvas, see CANVAS).
Follower ids ($3B walk closer, $3D run, $3E jump, $41 turn) are measured on
route-bot-trace.csv (frames 2042-2240: Dixie anims 222/224/225 = $3B/$3D/$3E + $A3).
Writes data/original/pirate/dixie_animation.lua and diddy_follower_animation.lua; the
atlas gets single inserted entries (never import_pirate_panic.write_atlas).
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(ROOT / "tools"))
import export_diddy_moves as moves  # noqa: E402
import export_items as items  # noqa: E402
from gfx_convert import load_palette  # noqa: E402

DIXIE_OFFSET = 0xA3
FOLLOWER_IDS = (0x3B, 0x3D, 0x3E, 0x41)
# Team-up: $1D-$24 leader carrying the partner, $20 carried, $26/$27 throw, $28 landed
# after the throw, $40 partner jumps on (team-throw-probe.csv, team_throw_capture.lua).
TEAM_IDS = tuple(range(0x1D, 0x29)) + (0x40,)
PLAYER_IDS = moves.BASE_IDS + moves.EXTRA_IDS
# $0B GlideDown (Dixie's helicopter spin, B8C95B) and $3C, the door walk (state $33,
# kabin-route-t1.csv: anim 60 = $3C + 0 for Diddy).
GLIDE_IDS, DOOR_IDS = (0x0B,), (0x3C,)
# SELECT swap (swap-route-t1.csv): the new leader plays $49 then $4A, the old one hops
# behind it with $4B (Diddy anim 73/74, Dixie 238 = $4B + $A3).
SWAP_IDS = (0x49, 0x4A, 0x4B)
# Dixie's ponytail poses overflow the 88x88 canvas: 128x128 keeps the same canvas-centre
# offset as the Diddy canvas (origin + 20 px both ways), so the renderer offsets still apply.
CANVAS, ORIGIN = 128, (moves.ORIGIN[0] + 20, moves.ORIGIN[1] + 20)


def render_pose(name, palette):
    image, origin_x, origin_y = items.render(name, palette)
    canvas = moves.Image.new("RGBA", (CANVAS, CANVAS))
    canvas.alpha_composite(image.convert("RGBA"), (ORIGIN[0] - origin_x, ORIGIN[1] - origin_y))
    return canvas


def carried_poses(rom, ids, offset):
    """Pose ids the leader's $8A frames give the carried Kong (drawn with that Kong's colours)."""
    return {op["arg2"] for index in ids for op in moves.script(rom, index + offset)["code"].values()
            if op["op"] == 0x8A}


def export_kong(rom, name_of, prefix, palette_file, ids, offset, out, extra_poses=()):
    palette = load_palette(str(items.SOURCE / "Palettes" / palette_file))
    scripts = {index: moves.script(rom, index + offset) for index in ids}
    poses, added = {}, []
    for pose in sorted(extra_poses):
        anim = "%s_pose_%04x" % (prefix, pose)
        gfx = name_of(pose)
        (render_pose(gfx, palette) if prefix == "dixie" else moves.render_pose(rom, gfx, palette)).save(
            moves.POSES / (anim + "_01.png"))
        poses[pose] = (anim, gfx)
        added.append(anim)
    for data in scripts.values():
        for op in data["code"].values():
            if (op["op"] < 0x80 or op["op"] in (0x8B, 0x89, 0x8A)) and op["arg"] not in poses:
                anim = "%s_pose_%04x" % (prefix, op["arg"])
                gfx = name_of(op["arg"])
                (render_pose(gfx, palette) if prefix == "dixie" else moves.render_pose(rom, gfx, palette)).save(moves.POSES / (anim + "_01.png"))
                poses[op["arg"]] = (anim, gfx)
                added.append(anim)
            if op["op"] == 0x90 and op["arg2"] + offset not in [i + offset for i in scripts]:
                print("note: %s script %#x switches to unexported %#x" % (prefix, data["start"], op["arg2"]))
    lines = ["-- Generated by tools/replay-compare/export_dixie.py (original ROM bytecode).", "return { scripts = {"]
    for index, data in scripts.items():
        lines.append("[%d] = { start = %d, flags = %d, code = {" % (index, data["start"], data["flags"]))
        for pc, op in data["code"].items():
            extra = "".join(", %s = %d" % (key, op[key]) for key in ("dur", "dx", "dy", "arg2", "slot") if key in op)
            lines.append("[%d] = { op = %d, arg = %d, next = %d%s }," % (pc, op["op"], op["arg"], op["next"], extra))
        lines.append("} },")
    lines.append("}, poses = {")
    for index, (anim, gfx) in sorted(poses.items()):
        lines.append('[%d] = { animation = "%s", gfx = "%s" },' % (index, anim, gfx))
    lines.append("} }")
    (ROOT / "data/original/pirate" / out).write_text("\n".join(lines) + "\n", encoding="utf-8")
    moves.insert_atlas(added)
    return {hex(k): v["status"] for k, v in scripts.items() if v["status"] != "exported"}, len(added)


def export():
    rom = items.ROM.read_bytes()
    name_of = items.pose_names(rom)
    return {
        "dixie": export_kong(rom, name_of, "dixie", "Sprite_Dixie_Active.bin", PLAYER_IDS + GLIDE_IDS + DOOR_IDS + SWAP_IDS + FOLLOWER_IDS + TEAM_IDS,
                             DIXIE_OFFSET, "dixie_animation.lua", carried_poses(rom, TEAM_IDS, 0)),
        "diddy_follower": export_kong(rom, name_of, "diddy", "Sprite_Diddy_Active.bin", FOLLOWER_IDS + DOOR_IDS + SWAP_IDS + TEAM_IDS, 0,
                                      "diddy_follower_animation.lua", carried_poses(rom, TEAM_IDS, DIXIE_OFFSET)),
    }


if __name__ == "__main__":
    for kong, report in export().items():
        print(kong, report)
