"""Export Pirate Panic walkers (Neek, Klomp) from their spawn and F9 animation scripts.

Writes data/original/pirate/walkers.lua (spawn fields, species table, animation op lists)
and the pose images under assets/images/pirate/walkers. The controller logic lives in
main/original_walkers.lua; see docs/delivery/NEXT_FIDELITY_GATE.md for the evidence.
Animation ops: `n < $80` pose for n frames; `$80` loop; `$81 cb` call; `$83 cb` call
that may hold the current pose; `$84 cb` set (and call) the per-frame routine; `$8E`
sound; `$90 cb,anim` call then switch animation.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))
import export_items as items  # noqa: E402
from gfx_convert import load_palette  # noqa: E402

OUT = ROOT / "assets/images/pirate/walkers"
LEVEL = ROOT / "data/original/pirate/pirate_panic_level.lua"
SPECIES = {0x027E: "Neek", 0x0294: "Klomp"}  # DATA_FF027E / DATA_FF0294 (bank $FF)
# Callback addresses (bank $B9) -> names used by main/original_walkers.lua.
CALLBACKS = {0xE67B: "quarter_speed", 0xE688: "boost_speed", 0xE694: "turn_check_161",
             0xE5AD: "squeak_turn_check_170", 0xEF1F: "stop", 0xE01B: "flip",
             0xE553: "hold_while_rising", 0xD12B: "hold", 0xE577: "none"}
ANIMATIONS = (0x160, 0x161, 0x162, 0x16F, 0x170, 0x171)


def ops(rom, number):
    pc = items.word(rom, 0x390000 + number * 4)
    out = []
    for _ in range(64):
        op = rom[0x390000 + pc]
        arg = items.word(rom, 0x390000 + pc + 1)
        if op < 0x80:
            out.append(("frame", op, arg))
            pc += 3
        elif op == 0x80:
            out.append(("loop",))
            return out
        elif op in (0x81, 0x83, 0x84):
            out.append(({0x81: "call", 0x83: "wait", 0x84: "per_frame"}[op], CALLBACKS[arg]))
            pc += 3
        elif op == 0x8E:
            out.append(("sound", arg & 0xFF))
            pc += 3
        elif op == 0x90:
            out.append(("switch", CALLBACKS[arg], items.word(rom, 0x390000 + pc + 3)))
            return out
        else:
            raise ValueError("unsupported animation opcode %02x in %x" % (op, number))
    raise ValueError("animation %x too long" % number)


def species_table(rom, address):
    base = items.importer.DEF_BANK_FILE_OFFSET + address
    return [items.word(rom, base + 2 * i) for i in range(8)]


def hitbox(rom, pose):
    """DATA_BCB600[pose / 2] -> {dx, dy, w, h} relative to the sprite (BCFC4D/BCFC59)."""
    pointer = items.word(rom, 0x3CB600 + pose // 2)
    return [(lambda v: v - 0x10000 if v & 0x8000 else v)(items.word(rom, 0x3C0000 + pointer + 2 * i))
            for i in range(4)]


def export_hitboxes(rom, poses):
    """data/original/pirate/hitboxes.lua for the walker poses and every Diddy pose
    (route-bot-contact.csv: enemy boxes 35/35; player box at frames 565/937)."""
    player = (ROOT / "data/original/pirate/animation_scripts.lua").read_text(encoding="utf-8")
    player_poses = {int(p) for p in re.findall(r"^\[(\d+)\] = \{ animation = ", player.split("poses = {", 1)[1], re.M)}
    lines = ["-- Generated by tools/replay-compare/export_walkers.py: pose -> { dx, dy, w, h } (DATA_BCB600).",
             "return {"]
    for pose in sorted(set(poses) | player_poses):
        lines.append("  [%d] = { %d, %d, %d, %d }," % ((pose,) + tuple(hitbox(rom, pose))))
    lines.append("}")
    (ROOT / "data/original/pirate/hitboxes.lua").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return len(lines) - 3


def export():
    rom = items.ROM.read_bytes()
    name_of = items.pose_names(rom)
    OUT.mkdir(parents=True, exist_ok=True)
    spawns, poses, palettes = {}, {}, {}
    level = LEVEL.read_text(encoding="utf-8")
    params = sorted({int(p) for p in re.findall(r"param = (\d+), sprite = '(?:Neek|Klomp)'", level)})
    for param in params:
        spawn = items.spawn_fields(rom, param)
        fields = spawn["fields"]
        species = SPECIES[fields[0x54]]
        spawns[param] = {"species": species, "animation": spawn["animation"],
                         "attributes": spawn["op85"], "target": fields[0x26],
                         "range": fields.get(0x46, 0), "move": fields[0x52],
                         "spawn_ahead": fields[0x30], "table": fields[0x54]}
        palettes[species] = items.palette_file(spawn["palette"])
    animations = {number: ops(rom, number) for number in ANIMATIONS}
    owner = {0x160: "Klomp", 0x161: "Klomp", 0x162: "Klomp", 0x16F: "Neek", 0x170: "Neek", 0x171: "Neek"}
    for number, script in animations.items():
        palette = load_palette(str(items.SOURCE / "Palettes" / palettes[owner[number]]))
        for op in script:
            if op[0] == "frame" and op[2] not in poses:
                image, origin_x, origin_y = items.render(name_of(op[2]), palette)
                sprite = "original_walker_%04x" % op[2]
                image.save(OUT / (sprite + ".png"))
                poses[op[2]] = (sprite, origin_x, origin_y, image.width, image.height)
    lines = ["-- Generated by tools/replay-compare/export_walkers.py (spawn + F9 animation scripts).",
             "return { spawns = {"]
    for param, s in spawns.items():
        lines.append('  [%d] = { species = "%s", animation = %d, attributes = %d, target = %d, range = %d, '
                     'move = %d, spawn_ahead = %d },' % (param, s["species"], s["animation"], s["attributes"],
                                                         s["target"], s["range"], s["move"], s["spawn_ahead"]))
    lines.append("}, species = {")
    for address, name in SPECIES.items():
        gravity, max_fall, accel = species_table(rom, address)[:3]
        lines.append('  %s = { gravity = %d, max_fall = %d, accel = %d, defeat = %d },'
                     % (name, gravity, max_fall, accel, species_table(rom, address)[5]))
    lines.append("}, animations = {")
    for number, script in animations.items():
        parts = []
        for op in script:
            parts.append("{ %s }" % ", ".join('"%s"' % v if isinstance(v, str) else str(v) for v in op))
        lines.append("  [%d] = { %s }," % (number, ", ".join(parts)))
    lines.append("}, poses = {")
    for pose, (sprite, ox, oy, width, height) in sorted(poses.items()):
        lines.append('  [%d] = { sprite = "%s", origin_x = %d, origin_y = %d, width = %d, height = %d },'
                     % (pose, sprite, ox, oy, width, height))
    lines.append("} }")
    (ROOT / "data/original/pirate/walkers.lua").write_text("\n".join(lines) + "\n", encoding="utf-8")
    item_poses = {int(p) for p in re.findall(r"pose = (\d+) \}", (ROOT / "data/original/pirate/items.lua").read_text())}
    print(export_hitboxes(rom, set(poses) | item_poses), "hitboxes")
    return spawns, animations, poses


if __name__ == "__main__":
    spawns, animations, poses = export()
    print(spawns)
    print(len(poses), "poses")
