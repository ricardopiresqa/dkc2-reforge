"""Export Pirate Panic's green Klobber (barrel $1AC + body $1E8) for main/original_klobber.lua.

Animations (F9): barrel idle $2E2; body emerge $1F4, run $1F5, turn $1F6, hop/return $1F7.
`$8D dur,body,barrel,x` frames carry both layers (the body drives the barrel's pose).
Poses render with gfx_assemble: body with Sprite_GreenKlobber, barrel with Sprite_Barrel.
Hitboxes from DATA_BCB600 (export_walkers.hitbox). Evidence of timing: route-bot-klobber.csv.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(ROOT / "tools"))
import export_diddy_moves as moves  # noqa: E402
import export_items as items  # noqa: E402
import export_walkers as walkers  # noqa: E402
from gfx_convert import load_palette  # noqa: E402

OUT = ROOT / "assets/images/pirate/klobber"
ANIMATIONS = (0x2E2, 0x1F4, 0x1F5, 0x1F6, 0x1F7)
CALLBACKS = {0xE5F0: "is_tnt", 0xE5F6: "run_frame", 0xE603: "emerged", 0xE616: "none", 0xE630: "sound",
             0xD12B: "hold"}


def script(rom, number):
    moves.SIZES[0x8D] = 8
    word = lambda offset: int.from_bytes(rom[offset:offset + 2], "little")
    data = moves.script(rom, number)
    for pc, op in data["code"].items():
        if op["op"] == 0x8D:
            base = 0x390000 + pc
            op.update(dur=rom[base + 1], arg=word(base + 2), arg2=word(base + 4))
    return data


def export():
    rom = items.ROM.read_bytes()
    name_of = items.pose_names(rom)
    body_palette = load_palette(str(items.SOURCE / "Palettes" / "Sprite_GreenKlobber.bin"))
    barrel_palette = load_palette(str(items.SOURCE / "Palettes" / "Sprite_Barrel.bin"))
    OUT.mkdir(parents=True, exist_ok=True)
    scripts = {number: script(rom, number) for number in ANIMATIONS}
    poses = {}

    def add(pose, palette):
        if pose in poses or pose == 0:
            return
        image, origin_x, origin_y = items.render(name_of(pose), palette)
        sprite = "original_klobber_%04x" % pose
        image.save(OUT / (sprite + ".png"))
        poses[pose] = (sprite, origin_x, origin_y, image.width, image.height, walkers.hitbox(rom, pose))

    for number, data in scripts.items():
        for op in data["code"].values():
            if op["op"] < 0x80:
                add(op["arg"], barrel_palette if number == 0x2E2 else body_palette)
            elif op["op"] == 0x8D:
                add(op["arg"], body_palette)
                add(op["arg2"], barrel_palette)
    lines = ["-- Generated by tools/replay-compare/export_klobber.py (F9 scripts + DATA_BCB600).",
             "return { animations = {"]
    for number, data in scripts.items():
        lines.append("  [%d] = { start = %d, code = {" % (number, data["start"]))
        for pc, op in data["code"].items():
            fields = ["op = %d" % op["op"], "arg = %d" % op["arg"], "next = %d" % op["next"]]
            fields += ["%s = %d" % (key, op[key]) for key in ("dur", "arg2") if key in op]
            if op["op"] in (0x81, 0x84, 0x8F, 0x90, 0x83):
                fields.append('call = "%s"' % CALLBACKS.get(op["arg"], "unknown_%04x" % op["arg"]))
            lines.append("    [%d] = { %s }," % (pc, ", ".join(fields)))
        lines.append("  } },")
    lines.append("}, poses = {")
    for pose, (sprite, ox, oy, width, height, box) in sorted(poses.items()):
        lines.append('  [%d] = { sprite = "%s", origin_x = %d, origin_y = %d, width = %d, height = %d, box = { %d, %d, %d, %d } },'
                     % ((pose, sprite, ox, oy, width, height) + tuple(box)))
    lines.append("} }")
    (ROOT / "data/original/pirate/klobber.lua").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return scripts, poses


if __name__ == "__main__":
    scripts, poses = export()
    print({hex(k): v["status"] for k, v in scripts.items()}, len(poses), "poses")
