def disasm_line(offset, indent=0):
    op = data[offset]
    name = OPCODES.get(op, f"??${op:02X}")
    length = LEN.get(op, 1)
    extra = ""
    if length == 2:
        extra = f"${data[offset+1]:02X}"
    elif length == 3:
        extra = f"${data[offset+1] | (data[offset+2] << 8):04X}"
    elif length == 4:
        extra = f"${data[offset+1] | (data[offset+2] << 8) | (data[offset+3] << 16):06X}"
    return f"  ${0xC00000|offset:06X}: {'  '*indent}{name:7s} {extra}", length

